// PLU Lookup Funktion
export function lookupPLU(code) {
  // PLU codes sind 4-5 stellig
  // Bio-Produkte starten mit 9 (z.B. 94011 = Bio Banane)
  const cleanCode = code.toString().trim();

  // Bio-Prefix entfernen (9xxxx → xxxx)
  const normalizedCode = cleanCode.startsWith('9') && cleanCode.length === 5
    ? cleanCode.slice(1)
    : cleanCode;

  const product = pluDatabase[normalizedCode] || pluDatabase[cleanCode];
  if (!product) return null;

  return {
    ...product,
    category: 'Obst & Gemüse',
    isBio: cleanCode.startsWith('9') && cleanCode.length === 5,
  };
}